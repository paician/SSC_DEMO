export const SUPPORTED_LOCALES = Object.freeze(['zh-CN', 'en-US']);
const DICTS = Object.freeze({ 'zh-CN': ZH_CN, 'en-US': EN });

function normalize(value) {
  if (!value) return null;
  const normalized = String(value).trim().replaceAll('_', '-').toLowerCase();
  if (normalized.startsWith('zh-tw') || normalized.startsWith('zh-hant')) return 'zh-CN';
  if (normalized.startsWith('zh-cn') || normalized.startsWith('zh-hans') || normalized === 'zh') return 'zh-CN';
  if (normalized.startsWith('en')) return 'en-US';
  return null;
}

export const LOCALE_STORAGE_KEY = 'portal_lang';

export function localeUrl(href, requestedLocale) {
  const url = new URL(href);
  const selected = normalize(requestedLocale);
  if (selected) url.searchParams.set('lang', selected);
  return url.href;
}

export function resolveLocale() {
  const queryLocale = normalize(new URLSearchParams(location.search).get('lang'));
  if (queryLocale) return queryLocale;
  let storedLocale = null;
  try {
    storedLocale = normalize(globalThis.localStorage?.getItem(LOCALE_STORAGE_KEY));
  } catch {}
  if (storedLocale) return storedLocale;
  const injectedLocale = normalize(window.__FIN_SSC_PORTAL__?.locale || window.__FIN_SSC_PORTAL__?.larkClientLanguage);
  if (injectedLocale) return injectedLocale;
  for (const item of navigator.languages || []) {
    const browserLocale = normalize(item);
    if (browserLocale) return browserLocale;
  }
  return normalize(navigator.language) || 'zh-CN';
}

export function createTranslator(locale = resolveLocale()) {
  const selected = DICTS[locale] ? locale : 'zh-CN';
  const dictionaryValue = DICTS[selected];
  const t = (key, vars = {}) => {
    let text = dictionaryValue[key] ?? ZH_CN[key] ?? key;
    Object.entries(vars).forEach(([name, value]) => {
      text = text.replaceAll('{' + name + '}', String(value));
    });
    return text;
  };
  return Object.freeze({ locale: selected, t });
}
